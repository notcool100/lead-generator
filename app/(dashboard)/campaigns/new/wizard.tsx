"use client";

import { useRouter } from "next/navigation";
import { useState } from "react";
import { Check } from "lucide-react";
import { Button } from "@/components/ui/button";
import { Card, CardContent } from "@/components/ui/card";
import { Checkbox, Field, Input, Select } from "@/components/ui/input";
import { cn } from "@/lib/utils";

const STEPS = [
  "Name", "Country", "City / region", "Category", "Data sources", "Lead limit", "Website criteria", "Previews", "Outreach", "Daily limit", "Launch",
];

export interface SourceOption {
  key: string;
  label: string;
  description: string;
  ok: boolean;
  reason?: string;
  default: boolean;
}

const CATEGORIES = ["restaurant", "cafe", "hotel", "bar", "gym", "salon", "dentist", "event venue", "real estate", "professional services"];

const WEBSITE_OPTIONS = [
  { value: "no_website", label: "No website", description: "No official website could be found" },
  { value: "poor_website", label: "Poor website", description: "Scored below 50 in the automated check" },
  { value: "outdated", label: "Outdated website", description: "Old copyright, no mobile layout, legacy tech" },
  { value: "unreachable", label: "Unreachable website", description: "Listed site is down or erroring" },
  { value: "good_website", label: "Good website", description: "Usually not worth targeting" },
];

interface State {
  name: string; country: string; city: string; region: string; category: string; customCategory: string;
  leadSources: string[]; maxLeads: number; targetWebsiteStatuses: string[]; minLeadScore: number;
  autoGeneratePreview: boolean; autoGenerateDrafts: boolean; autoSendEnabled: boolean; dailyEmailLimit: number;
}

export function CampaignWizard({ sources }: { sources: SourceOption[] }) {
  const router = useRouter();
  const [step, setStep] = useState(0);
  const [error, setError] = useState<string | null>(null);
  const [pending, setPending] = useState(false);
  const [s, setS] = useState<State>({
    name: "", country: "", city: "", region: "", category: "restaurant", customCategory: "",
    leadSources: sources.filter((x) => x.ok && x.default && x.key !== "mock").map((x) => x.key),
    maxLeads: 50, targetWebsiteStatuses: ["no_website", "poor_website", "outdated"], minLeadScore: 50,
    autoGeneratePreview: true, autoGenerateDrafts: true, autoSendEnabled: false, dailyEmailLimit: 20,
  });
  const set = <K extends keyof State>(k: K, v: State[K]) => setS((p) => ({ ...p, [k]: v }));
  const category = s.category === "other" ? s.customCategory.trim() : s.category;

  const valid = [
    s.name.trim().length >= 2, s.country.trim().length >= 2, s.city.trim().length > 0 || s.region.trim().length > 0, category.length >= 2, s.leadSources.length > 0,
    s.maxLeads >= 1 && s.maxLeads <= 1000, s.targetWebsiteStatuses.length > 0, true, true, s.dailyEmailLimit >= 0, true,
  ];

  async function submit(launch: boolean) {
    setPending(true);
    setError(null);
    const res = await fetch("/api/campaigns", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        name: s.name, country: s.country, city: s.city || null, region: s.region || null, category,
        leadSources: s.leadSources, maxLeads: s.maxLeads, targetWebsiteStatuses: s.targetWebsiteStatuses, minLeadScore: s.minLeadScore,
        autoGeneratePreview: s.autoGeneratePreview, autoGenerateDrafts: s.autoGenerateDrafts, autoSendEnabled: s.autoSendEnabled,
        dailyEmailLimit: s.dailyEmailLimit, launch,
      }),
    });
    const data = (await res.json()) as { campaign?: { id: string }; error?: string };
    if (!res.ok || !data.campaign) {
      setError(data.error ?? "Could not create campaign");
      setPending(false);
      return;
    }
    router.push(`/campaigns/${data.campaign.id}`);
  }

  return (
    <div className="grid gap-6 lg:grid-cols-[220px_1fr]">
      <ol className="space-y-1">
        {STEPS.map((label, i) => (
          <li key={label}>
            <button
              type="button"
              onClick={() => i <= step || valid.slice(0, i).every(Boolean) ? setStep(i) : null}
              className={cn("flex w-full items-center gap-3 rounded-md px-3 py-2 text-left text-sm", i === step ? "bg-card font-medium shadow-sm ring-1 ring-border" : "text-muted-foreground hover:bg-muted")}
            >
              <span className={cn("grid size-5 place-items-center rounded-full text-[10px] font-semibold", i < step ? "bg-primary text-primary-foreground" : "bg-muted text-muted-foreground")}>
                {i < step ? <Check className="size-3" /> : i + 1}
              </span>
              {label}
            </button>
          </li>
        ))}
      </ol>

      <Card>
        <CardContent className="grid gap-5 p-6">
          <p className="text-xs font-medium uppercase tracking-wide text-muted-foreground">Step {step + 1} of {STEPS.length}</p>
          {step === 0 && (
            <Field label="Campaign name" hint="Internal name, e.g. “Lisbon restaurants — Q4”.">
              <Input autoFocus value={s.name} onChange={(e) => set("name", e.target.value)} placeholder="Lisbon restaurants" />
            </Field>
          )}
          {step === 1 && (
            <Field label="Target country" hint="Make sure outreach to businesses in this country is lawful for you (e.g. GDPR/PECR in the EU/UK, CAN-SPAM in the US).">
              <Input autoFocus value={s.country} onChange={(e) => set("country", e.target.value)} placeholder="Portugal" />
            </Field>
          )}
          {step === 2 && (
            <div className="grid gap-4 sm:grid-cols-2">
              <Field label="City"><Input autoFocus value={s.city} onChange={(e) => set("city", e.target.value)} placeholder="Lisbon" /></Field>
              <Field label="Region (optional)"><Input value={s.region} onChange={(e) => set("region", e.target.value)} placeholder="Lisboa" /></Field>
            </div>
          )}
          {step === 3 && (
            <div className="grid gap-4">
              <Field label="Business category">
                <Select value={s.category} onChange={(e) => set("category", e.target.value)}>
                  {CATEGORIES.map((c) => <option key={c} value={c}>{c.charAt(0).toUpperCase() + c.slice(1)}</option>)}
                  <option value="other">Other…</option>
                </Select>
              </Field>
              {s.category === "other" && (
                <Field label="Custom category" hint="A small AI model maps custom categories to the closest template.">
                  <Input value={s.customCategory} onChange={(e) => set("customCategory", e.target.value)} placeholder="florist" />
                </Field>
              )}
            </div>
          )}
          {step === 4 && (
            <div className="grid gap-2">
              <p className="text-sm text-muted-foreground">Where to look for businesses. Results from all selected sources are merged and de-duplicated; a business found in several sources gets its missing details filled in.</p>
              {sources.map((o) => (
                <Checkbox
                  key={o.key}
                  label={o.ok ? o.label : `${o.label} — unavailable`}
                  description={o.ok ? o.description : `${o.description} (${o.reason})`}
                  disabled={!o.ok}
                  checked={s.leadSources.includes(o.key)}
                  onChange={(e) => set("leadSources", e.target.checked ? [...s.leadSources, o.key] : s.leadSources.filter((x) => x !== o.key))}
                />
              ))}
            </div>
          )}
          {step === 5 && (
            <Field label="Maximum leads (total)" hint="Leads are fetched 20 at a time — the first 20 on launch, then “Discover next 20” on the campaign page — until this total is reached.">
              <Input type="number" min={1} max={1000} value={s.maxLeads} onChange={(e) => set("maxLeads", Number(e.target.value))} />
            </Field>
          )}
          {step === 6 && (
            <div className="grid gap-4">
              <p className="text-sm text-muted-foreground">Leads qualify when their verified website status is one of:</p>
              <div className="grid gap-2 sm:grid-cols-2">
                {WEBSITE_OPTIONS.map((o) => (
                  <Checkbox
                    key={o.value}
                    label={o.label}
                    description={o.description}
                    checked={s.targetWebsiteStatuses.includes(o.value)}
                    onChange={(e) => set("targetWebsiteStatuses", e.target.checked ? [...s.targetWebsiteStatuses, o.value] : s.targetWebsiteStatuses.filter((x) => x !== o.value))}
                  />
                ))}
              </div>
              <Field label="Minimum lead score" hint="0–100, combines website opportunity, contactability and reputation.">
                <Input type="number" min={0} max={100} value={s.minLeadScore} onChange={(e) => set("minLeadScore", Number(e.target.value))} />
              </Field>
            </div>
          )}
          {step === 7 && (
            <Checkbox label="Generate previews automatically" description="Qualified leads get an AI analysis and a website concept deployed to a unique URL." checked={s.autoGeneratePreview} onChange={(e) => set("autoGeneratePreview", e.target.checked)} />
          )}
          {step === 8 && (
            <div className="grid gap-3">
              <Checkbox label="Generate email drafts" description="Drafts wait in the Outreach queue for review." checked={s.autoGenerateDrafts} onChange={(e) => set("autoGenerateDrafts", e.target.checked)} />
              <Checkbox label="Auto-send (not recommended)" description="Only takes effect if “Require approval” is switched off in Settings → Compliance. All sending limits and suppression rules still apply." checked={s.autoSendEnabled} onChange={(e) => set("autoSendEnabled", e.target.checked)} />
            </div>
          )}
          {step === 9 && (
            <Field label="Daily email limit for this campaign" hint="Global hourly/daily/per-domain limits from Settings also apply.">
              <Input type="number" min={0} max={1000} value={s.dailyEmailLimit} onChange={(e) => set("dailyEmailLimit", Number(e.target.value))} />
            </Field>
          )}
          {step === 10 && (
            <div className="grid gap-2 text-sm">
              <Summary k="Name" v={s.name} />
              <Summary k="Target" v={`${category} in ${[s.city, s.region, s.country].filter(Boolean).join(", ")}`} />
              <Summary k="Sources" v={s.leadSources.map((k) => sources.find((x) => x.key === k)?.label ?? k).join(", ")} />
              <Summary k="Lead limit" v={String(s.maxLeads)} />
              <Summary k="Website criteria" v={s.targetWebsiteStatuses.join(", ").replace(/_/g, " ")} />
              <Summary k="Min lead score" v={String(s.minLeadScore)} />
              <Summary k="Previews" v={s.autoGeneratePreview ? "Automatic" : "Manual"} />
              <Summary k="Drafts" v={s.autoGenerateDrafts ? "Automatic" : "Manual"} />
              <Summary k="Sending" v={s.autoSendEnabled ? "Auto-send (if approval disabled globally)" : "Human approval"} />
              <Summary k="Daily limit" v={String(s.dailyEmailLimit)} />
            </div>
          )}

          {error ? <p className="text-sm text-destructive">{error}</p> : null}
          <div className="flex justify-between border-t pt-5">
            <Button variant="ghost" onClick={() => setStep((x) => Math.max(0, x - 1))} disabled={step === 0}>Back</Button>
            {step < STEPS.length - 1 ? (
              <Button onClick={() => setStep((x) => x + 1)} disabled={!valid[step]}>Continue</Button>
            ) : (
              <div className="flex gap-2">
                <Button variant="outline" disabled={pending} onClick={() => submit(false)}>Save as draft</Button>
                <Button disabled={pending || !valid.every(Boolean)} onClick={() => submit(true)}>{pending ? "Launching…" : "Launch campaign"}</Button>
              </div>
            )}
          </div>
        </CardContent>
      </Card>
    </div>
  );
}

function Summary({ k, v }: { k: string; v: string }) {
  return (
    <div className="grid grid-cols-[160px_1fr] border-b py-2 last:border-0">
      <span className="text-muted-foreground">{k}</span>
      <span className="font-medium capitalize">{v || "—"}</span>
    </div>
  );
}
