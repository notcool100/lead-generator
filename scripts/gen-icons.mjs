// Generates templates/icons.ts from @phosphor-icons/core (MIT). Run: node scripts/gen-icons.mjs
import { readFileSync, writeFileSync } from "node:fs";
const base = "node_modules/@phosphor-icons/core/assets";
const icons = {
  phone: "light/phone-light", mail: "light/envelope-simple-light", pin: "light/map-pin-light", clock: "light/clock-light",
  calendar: "light/calendar-blank-light", arrowRight: "regular/arrow-right", arrowUpRight: "regular/arrow-up-right",
  check: "regular/check", instagram: "light/instagram-logo-light", facebook: "light/facebook-logo-light",
  tiktok: "light/tiktok-logo-light", navigation: "light/navigation-arrow-light", sparkle: "light/sparkle-light",
  quotes: "fill/quotes-fill", star: "fill/star-fill", starHalf: "fill/star-half-fill", starEmpty: "light/star-light",
};
const out = {};
for (const [name, file] of Object.entries(icons)) {
  const svg = readFileSync(`${base}/${file}.svg`, "utf8");
  out[name] = svg.match(/<svg[^>]*>([\s\S]*)<\/svg>/)[1].trim();
}
writeFileSync(
  "templates/icons.ts",
  `// Generated by scripts/gen-icons.mjs from @phosphor-icons/core (MIT license). Do not edit by hand.\n` +
    `export const ICON_PATHS = ${JSON.stringify(out, null, 2)} as const;\n` +
    `export type IconName = keyof typeof ICON_PATHS;\n\n` +
    `export function icon(name: IconName, cls = "icon"): string {\n` +
    `  return \`<svg class="\${cls}" viewBox="0 0 256 256" fill="currentColor" aria-hidden="true">\${ICON_PATHS[name]}</svg>\`;\n}\n`,
);
console.log("icons:", Object.keys(out).length);
