import { z } from "zod";

const websiteStatus = z.enum(["unknown", "no_website", "poor_website", "outdated", "good_website", "excellent_website", "unreachable"]);

export const CampaignCreateSchema = z.object({
  name: z.string().trim().min(2).max(120),
  category: z.string().trim().min(2).max(80),
  country: z.string().trim().min(2).max(80),
  region: z.string().trim().max(80).optional().nullable(),
  city: z.string().trim().max(80).optional().nullable(),
  maxLeads: z.number().int().min(1).max(1000),
  targetWebsiteStatuses: z.array(websiteStatus).min(1),
  minLeadScore: z.number().int().min(0).max(100).default(50),
  leadSources: z.array(z.enum(["google_places", "apify_google_maps", "openstreetmap", "web_search", "yelp", "mock"])).max(6).default([]),
  autoGeneratePreview: z.boolean().default(true),
  autoGenerateDrafts: z.boolean().default(true),
  autoSendEnabled: z.boolean().default(false),
  dailyEmailLimit: z.number().int().min(0).max(1000).default(20),
  launch: z.boolean().default(false),
});

export const CampaignUpdateSchema = CampaignCreateSchema.omit({ launch: true }).partial();

export const LeadListQuerySchema = z.object({
  q: z.string().max(100).optional(),
  status: z.string().max(40).optional(),
  websiteStatus: websiteStatus.optional(),
  campaignId: z.string().uuid().optional(),
  country: z.string().max(80).optional(),
  category: z.string().max(80).optional(),
  page: z.coerce.number().int().min(1).default(1),
  pageSize: z.coerce.number().int().min(1).max(100).default(25),
});

export const LeadStatusUpdateSchema = z.object({
  status: z.enum(["qualified", "rejected", "replied", "interested", "not_interested", "converted"]),
  note: z.string().max(500).optional(),
});

export const OutreachEditSchema = z.object({
  subject: z.string().trim().min(3).max(200),
  body: z.string().trim().min(20).max(5000),
});

export const SuppressSchema = z.object({ reason: z.string().trim().min(2).max(200).default("manual") });

export const SuppressionAddSchema = z.object({
  email: z.string().trim().email().max(200),
  reason: z.string().trim().min(2).max(200).default("manual"),
  campaignId: z.string().uuid().optional(),
});
