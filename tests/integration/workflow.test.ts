/**
 * End-to-end workflow against a real PostgreSQL database (TEST_DATABASE_URL),
 * with the mock lead/AI providers and an in-memory email provider. Jobs are
 * executed inline by draining the NextAction list each step returns.
 *
 *   createdb ai_lead_test
 *   DATABASE_URL=$TEST_DATABASE_URL pnpm db:deploy
 *   pnpm test:integration
 */
import http from "node:http";
import type { AddressInfo } from "node:net";
import { afterAll, beforeAll, describe, expect, it } from "vitest";

const enabled = Boolean(process.env.TEST_DATABASE_URL);

describe.skipIf(!enabled)("lead → preview → outreach → send → follow-up workflow", async () => {
  const { prisma } = await import("@/lib/db");
  const { setAIProviderForTests } = await import("@/providers/ai");
  const { MockAIProvider } = await import("@/providers/ai/MockAIProvider");
  const { setEmailProviderForTests } = await import("@/providers/email");
  const { LogEmailProvider } = await import("@/providers/email/LogEmailProvider");
  const { MockLeadProvider } = await import("@/providers/leads/MockLeadProvider");
  const { VpsDeploymentProvider } = await import("@/providers/deployment/VpsDeploymentProvider");
  const { discoverLeadsForCampaign } = await import("@/services/lead-discovery/discoveryService");
  const { runWebsiteCheck } = await import("@/services/website-analysis/websiteCheckService");
  const { WebsiteAnalyzer } = await import("@/services/website-analysis/WebsiteAnalyzer");
  const { analyzeBusiness } = await import("@/services/ai-analysis/BusinessAnalyzer");
  const { generatePreview } = await import("@/services/preview-generation/previewService");
  const { deployPreview } = await import("@/services/deployment/PreviewDeploymentService");
  const { generateOutreachDraft } = await import("@/services/outreach/OutreachGenerator");
  const { sendOutreachMessage, SendDeferredError } = await import("@/services/email/EmailSender");
  const { processDueFollowups } = await import("@/services/followups/followupService");
  const { handleEmailEvent } = await import("@/services/email/webhooks");
  const { saveSettings } = await import("@/services/compliance/settings");
  const { suppressEmail } = await import("@/services/compliance/suppression");
  type NextAction = import("@/queue/queues").NextAction;

  const email = new LogEmailProvider();
  const deploy = new VpsDeploymentProvider("./storage/test-previews");
  let server: http.Server;
  let campaignId: string;

  // Serves the mock "existing websites" so the analyzer exercises real HTTP.
  beforeAll(async () => {
    server = http.createServer((req, res) => {
      const variant = req.url?.split("?")[0].split("/").pop();
      const html = variant === "good"
        ? `<html><head><meta name="viewport" content="width=device-width"><title>Good</title><meta name="description" content="d"><meta property="og:title" content="x"><link rel="icon" href="/f"></head><body><h1>a</h1><h2>b</h2><h3>c</h3><p>${"words ".repeat(400)}</p><img src="a" alt="a"><a href="#">Book now</a><a href="mailto:x@y.pt">x</a></body></html>`
        : `<html><head><title>Old</title></head><body><table width="700"><tr><td width="700"><table><tr><td width="1">hi</td></tr></table></td></tr></table>© 2011</body></html>`;
      res.writeHead(200, { "Content-Type": "text/html" }).end(html);
    });
    await new Promise<void>((r) => server.listen(0, "127.0.0.1", () => r()));
    const base = `http://127.0.0.1:${(server.address() as AddressInfo).port}/mock-sites`;

    setAIProviderForTests(new MockAIProvider());
    setEmailProviderForTests(email);
    await prisma.$executeRawUnsafe(`TRUNCATE users, campaigns, leads, suppression_list, jobs, audit_logs, settings, ai_cache, website_templates CASCADE`);
    await saveSettings("compliance", { minDelaySeconds: 0, maxEmailsPerHour: 100, maxEmailsPerDay: 100, maxEmailsPerDomainPerDay: 100, maxFollowups: 2, followupDelayDays: [4, 8] });
    await saveSettings("general", { domainDiscoveryEnabled: false });
    const c = await prisma.campaign.create({
      data: { name: "IT", category: "restaurant", country: "Portugal", city: "Lisbon", status: "running", maxLeads: 12, autoGeneratePreview: true, autoGenerateDrafts: true, dailyEmailLimit: 100 },
    });
    campaignId = c.id;
    (globalThis as { __mockBase?: string }).__mockBase = base;
  });
  afterAll(async () => {
    server?.close();
    setAIProviderForTests(null);
    setEmailProviderForTests(null);
    await prisma.$disconnect();
  });

  async function drain(actions: NextAction[]) {
    const queue = [...actions];
    const seen: Record<string, number> = {};
    while (queue.length) {
      const a = queue.shift()!;
      seen[a.queue] = (seen[a.queue] ?? 0) + 1;
      const p = a.payload as Record<string, string>;
      let out: { next: NextAction[] } = { next: [] };
      if (a.queue === "website-analysis") out = await runWebsiteCheck(p.leadId, new WebsiteAnalyzer({ domainDiscovery: false }));
      else if (a.queue === "ai-analysis") out = await analyzeBusiness(p.leadId);
      else if (a.queue === "preview-generation") out = await generatePreview(p.leadId);
      else if (a.queue === "deployment") out = await deployPreview(p.previewId, deploy);
      else if (a.queue === "outreach-draft") out = await generateOutreachDraft(p.leadId, { sequenceNumber: Number(p.sequenceNumber ?? 0), followupId: p.followupId });
      queue.push(...out.next);
    }
    return seen;
  }

  it("discovers, de-duplicates and qualifies leads, then builds previews and drafts", async () => {
    const provider = new MockLeadProvider((globalThis as { __mockBase?: string }).__mockBase);
    const first = await discoverLeadsForCampaign(campaignId, provider);
    expect(first.created).toBe(12); // capped by maxLeads
    // Next run resumes from the saved cursor, fetches at most one batch of 20.
    await prisma.campaign.update({ where: { id: campaignId }, data: { maxLeads: 100 } });
    const second = await discoverLeadsForCampaign(campaignId, provider);
    expect(second.created).toBe(20);
    expect(second.duplicates).toBe(0);
    // Re-scanning from the start must not create duplicates.
    await prisma.campaign.update({ where: { id: campaignId }, data: { maxLeads: 44, discoveryCursor: null } });
    const rescan = await discoverLeadsForCampaign(campaignId, provider);
    expect(rescan.created).toBe(12);
    expect(rescan.duplicates).toBe(32);

    const seen = await drain([...first.next, ...second.next, ...rescan.next]);
    expect(seen["website-analysis"]).toBeGreaterThan(0);

    const leads = await prisma.lead.findMany({ where: { campaignId }, include: { websiteChecks: true } });
    for (const l of leads) {
      expect(l.websiteChecks.length).toBe(1);
      // Never claim "no website" when the provider listed one.
      if (l.websiteUrl) expect(l.websiteStatus).not.toBe("no_website");
      if (["good_website", "excellent_website"].includes(l.websiteStatus)) expect(l.status).toBe("rejected");
    }
    const withDraft = await prisma.outreachMessage.count({ where: { campaignId, status: "draft" } });
    expect(withDraft).toBeGreaterThan(0);
    expect(await prisma.websitePreview.count({ where: { deploymentStatus: "deployed" } })).toBeGreaterThan(0);
  }, 180_000);

  it("never sends without approval, sends after approval, and schedules a follow-up", async () => {
    const draft = await prisma.outreachMessage.findFirstOrThrow({ where: { campaignId, status: "draft" } });
    expect(draft.body).toContain("/p/");
    expect(draft.body).not.toContain("{{preview_url}}");

    const blocked = await sendOutreachMessage(draft.id, email);
    expect(blocked).toMatchObject({ skipped: expect.stringMatching(/not approved/) });

    const d2 = await prisma.outreachMessage.findFirstOrThrow({ where: { campaignId, status: "draft" } });
    await prisma.outreachMessage.update({ where: { id: d2.id }, data: { status: "approved", approvedAt: new Date() } });
    const res = await sendOutreachMessage(d2.id, email);
    expect(res).toMatchObject({ sent: true });
    const sent = email.sent.at(-1)!;
    expect(sent.text).toMatch(/Unsubscribe: http/);
    expect(sent.headers?.["List-Unsubscribe"]).toBeDefined();
    expect(await prisma.followup.count({ where: { previousMessageId: d2.id, status: "scheduled" } })).toBe(1);
  });

  it("enforces campaign daily limits by deferring", async () => {
    await prisma.campaign.update({ where: { id: campaignId }, data: { dailyEmailLimit: 1 } });
    const d = await prisma.outreachMessage.findFirstOrThrow({ where: { campaignId, status: "draft" } });
    await prisma.outreachMessage.update({ where: { id: d.id }, data: { status: "approved" } });
    await expect(sendOutreachMessage(d.id, email)).rejects.toBeInstanceOf(SendDeferredError);
    expect((await prisma.outreachMessage.findUniqueOrThrow({ where: { id: d.id } })).status).toBe("queued");
    await prisma.campaign.update({ where: { id: campaignId }, data: { dailyEmailLimit: 100 } });
  });

  it("drafts due follow-ups and stops the sequence after a reply", async () => {
    const f = await prisma.followup.findFirstOrThrow({ where: { status: "scheduled" } });
    const future = new Date(f.scheduledAt.getTime() + 1000);
    const due = await processDueFollowups(future);
    expect(due.drafted).toBe(1);
    await drain(due.next);
    const followupDraft = await prisma.outreachMessage.findFirstOrThrow({ where: { leadId: f.leadId, sequenceNumber: 1 } });
    expect(followupDraft.status).toBe("draft");

    const original = await prisma.outreachMessage.findUniqueOrThrow({ where: { id: f.previousMessageId } });
    await handleEmailEvent({ type: "replied", outreachMessageId: original.id });
    expect((await prisma.lead.findUniqueOrThrow({ where: { id: f.leadId } })).status).toBe("replied");
    expect((await prisma.outreachMessage.findUniqueOrThrow({ where: { id: followupDraft.id } })).status).toBe("cancelled");
  });

  it("unsubscribe / bounce suppress the address and block every future send", async () => {
    const sentMsg = await prisma.outreachMessage.findFirstOrThrow({ where: { status: "sent" }, include: { lead: true } });
    await handleEmailEvent({ type: "bounced", outreachMessageId: sentMsg.id, providerEventId: "evt-b1" });
    expect(await prisma.suppressionEntry.findUnique({ where: { email: sentMsg.toEmail! } })).not.toBeNull();
    // duplicate provider events are ignored
    expect(await handleEmailEvent({ type: "bounced", outreachMessageId: sentMsg.id, providerEventId: "evt-b1" })).toEqual({ ignored: "duplicate" });

    const other = await prisma.lead.findFirstOrThrow({ where: { campaignId, email: { not: null }, doNotContact: false, outreachMessages: { some: {} } } });
    await suppressEmail(other.email!, "unsubscribed", "test");
    const lead = await prisma.lead.findUniqueOrThrow({ where: { id: other.id }, include: { outreachMessages: true } });
    expect(lead.doNotContact).toBe(true);
    expect(lead.unsubscribed).toBe(true);
    expect(lead.outreachMessages.every((m) => ["cancelled", "sent", "rejected"].includes(m.status))).toBe(true);

    const m = await prisma.outreachMessage.create({ data: { leadId: lead.id, campaignId, subject: "x", body: "y", status: "approved", toEmail: lead.email } });
    const r = await sendOutreachMessage(m.id, email);
    expect(r).toMatchObject({ skipped: expect.stringMatching(/do_not_contact|unsubscribed|suppression/) });
  });
});
