import { prisma } from "@/lib/db";
import { leadEvent } from "@/lib/audit";
import { getDeploymentProvider, type DeploymentProvider } from "@/providers/deployment";
import type { NextAction } from "@/queue/queues";
import { renderPreviewHtml } from "@/templates/render";
import { PreviewConfigSchema } from "@/types/preview";

export async function deployPreview(previewId: string, provider: DeploymentProvider = getDeploymentProvider()): Promise<{ url: string; next: NextAction[] }> {
  const preview = await prisma.websitePreview.findUniqueOrThrow({ where: { id: previewId }, include: { lead: { include: { campaign: true } } } });
  await prisma.websitePreview.update({ where: { id: previewId }, data: { deploymentStatus: "building" } });

  try {
    const config = PreviewConfigSchema.parse(preview.generatedContent);
    const html = renderPreviewHtml(config);
    const result = await provider.deploy({ slug: preview.subdomain, html, version: preview.version });

    await prisma.websitePreview.update({
      where: { id: previewId },
      data: {
        deploymentStatus: "deployed",
        deploymentUrl: result.url,
        deploymentProvider: provider.name,
        sourcePath: result.sourcePath,
        lastDeployedAt: new Date(),
      },
    });
    const lead = preview.lead;
    const advance = ["analyzed", "preview_generating", "qualified"].includes(lead.status);
    if (advance) await prisma.lead.update({ where: { id: lead.id }, data: { status: "preview_ready" } });
    await leadEvent(lead.id, "preview_deployed", `Preview deployed: ${result.url}`);

    const auto = lead.campaign?.autoGenerateDrafts ?? false;
    const hasDraft = await prisma.outreachMessage.count({ where: { leadId: lead.id, sequenceNumber: 0, status: { in: ["draft", "approved", "queued", "sent"] } } });
    return { url: result.url, next: auto && !hasDraft && lead.email && !lead.doNotContact ? [{ queue: "outreach-draft", payload: { leadId: lead.id } }] : [] };
  } catch (err) {
    await prisma.websitePreview.update({ where: { id: previewId }, data: { deploymentStatus: "failed" } });
    throw err;
  }
}
